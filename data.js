export function audioKey(text) {
    return text
        .toLowerCase()
        .replace(/[^\p{L}\p{N}]+/gu, "-")
        .replace(/^-|-$/g, "");
}

export function emojiToCodepoint(emoji) {
    return Array.from(emoji)
        .map((c) => c.codePointAt(0).toString(16))
        .filter((hex) => hex !== "fe0f")
        .join("-");
}
